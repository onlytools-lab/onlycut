param([Parameter(Mandatory)][string]$OutputDirectory)
$ErrorActionPreference='Stop'
$root=Split-Path -Parent $PSScriptRoot
$output=[IO.Path]::GetFullPath($OutputDirectory)
$allowed=[IO.Path]::GetFullPath((Join-Path $root 'artifacts')) + [IO.Path]::DirectorySeparatorChar
if(!$output.StartsWith($allowed,[StringComparison]::OrdinalIgnoreCase) -or (Test-Path $output)){throw 'Twin requires a new directory inside artifacts'}
$payload=Join-Path $output 'payload'
New-Item -ItemType Directory $payload -Force | Out-Null
[xml]$props=Get-Content "$root\Directory.Build.props"
$version=[string]$props.Project.PropertyGroup.Version
dotnet publish "$root\CutPic.csproj" -c Release -r win-x64 --self-contained true --no-build --no-restore -o $payload
if($LASTEXITCODE -ne 0){throw 'Twin payload publish failed'}
wix build "$root\installer\Package.wxs" -arch x64 -d "RootDir=$root" -d "PublishDir=$payload" -d "ProductVersion=$version" -o "$output\same-version-twin.msi"
if($LASTEXITCODE -ne 0){throw 'Twin MSI failed'}
$metadata=& "$PSScriptRoot\inspect-msi.ps1" "$output\same-version-twin.msi"
$metadata | ConvertTo-Json -Depth 12 | Set-Content "$output\metadata.json" -Encoding utf8
Write-Host "Twin generated by WiX (not a patched MSI): $output"
